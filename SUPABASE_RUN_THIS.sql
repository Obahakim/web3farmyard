CREATE OR REPLACE FUNCTION public.subscribe_newsletter(p_email text, p_farmer_name text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  clean_email text := lower(btrim(p_email));
  clean_name text := btrim(p_farmer_name);
BEGIN
  IF clean_email IS NULL
    OR char_length(clean_email) > 254
    OR clean_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'
  THEN
    RAISE EXCEPTION 'A valid email address is required' USING ERRCODE = '22023';
  END IF;

  IF clean_name IS NULL OR char_length(clean_name) < 2 OR char_length(clean_name) > 40 THEN
    RAISE EXCEPTION 'Username must be between 2 and 40 characters' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.subscribers (email, farmer_name, subscribed, subscribed_at, created_at, updated_at)
  VALUES (clean_email, clean_name, true, now(), now(), now())
  ON CONFLICT ((lower(email))) DO UPDATE
    SET farmer_name = EXCLUDED.farmer_name,
        subscribed = true,
        subscribed_at = now(),
        unsubscribed_at = NULL,
        updated_at = now()
    WHERE public.subscribers.subscribed IS DISTINCT FROM true;

  IF NOT FOUND THEN
    RETURN 'already_subscribed';
  END IF;

  RETURN 'subscribed';
END;
$$;

