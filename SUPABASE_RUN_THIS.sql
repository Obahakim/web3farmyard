  ON public.chat_messages FOR SELECT TO anon, authenticated
  USING (true);
CREATE POLICY chat_messages_public_insert
  ON public.chat_messages FOR INSERT TO anon, authenticated
  WITH CHECK (
    char_length(btrim(coalesce(author, ''))) BETWEEN 2 AND 40
    AND char_length(btrim(coalesce(message, ''))) BETWEEN 1 AND 200
  );

CREATE POLICY analytics_events_public_insert
  ON public.analytics_events FOR INSERT TO anon, authenticated
  WITH CHECK (
    nullif(btrim(event_type), '') IS NOT NULL
    AND char_length(event_type) <= 80
    AND nullif(btrim(page), '') IS NOT NULL
    AND char_length(page) <= 2048
    AND (duration_ms IS NULL OR duration_ms >= 0)
  );

CREATE POLICY posts_public_read_published
