-- Replace existing policies on these application tables; this changes access rules only, not rows.
DO $$
DECLARE
  existing_policy record;
BEGIN
  FOR existing_policy IN
    SELECT schemaname, tablename, policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = ANY (ARRAY[
        'airdrops', 'junkyard', 'subscribers', 'farmer_profiles',
        'chat_messages', 'analytics_events', 'newsletter_sends', 'posts'
      ])
  LOOP
    EXECUTE format(
      'DROP POLICY %I ON %I.%I',
      existing_policy.policyname,
      existing_policy.schemaname,
      existing_policy.tablename
    );
  END LOOP;
END;
$$;

