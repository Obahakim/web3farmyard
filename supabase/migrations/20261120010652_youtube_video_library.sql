-- Web3Farmyard YouTube video library
-- Admin-managed records only. Public access will be added in a later phase.

BEGIN;
CREATE TABLE IF NOT EXISTS public.youtube_videos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  youtube_video_id text NOT NULL UNIQUE CHECK (youtube_video_id ~ '^[A-Za-z0-9_-]{11}$'),
  youtube_url text NOT NULL,
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 300),
  channel_title text NOT NULL CHECK (char_length(channel_title) BETWEEN 1 AND 200),
  thumbnail_url text NOT NULL,
  summary text NOT NULL DEFAULT '' CHECK (char_length(summary) <= 3000),
  difficulty text[] NOT NULL DEFAULT '{}' CHECK (difficulty <@ ARRAY['Beginner','Intermediate','Advanced']::text[]),
  categories text[] NOT NULL DEFAULT '{}',
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved','rejected')),
  is_featured boolean NOT NULL DEFAULT false,
  display_order integer NOT NULL DEFAULT 0 CHECK (display_order >= 0),
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS youtube_videos_public_order_idx ON public.youtube_videos (is_featured DESC, display_order ASC, published_at DESC) WHERE status = 'approved';
CREATE INDEX IF NOT EXISTS youtube_videos_status_idx ON public.youtube_videos (status, updated_at DESC);
ALTER TABLE public.youtube_videos ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.youtube_videos FROM anon, authenticated, PUBLIC;
REVOKE ALL PRIVILEGES ON SEQUENCE public.youtube_videos_id_seq FROM anon, authenticated, PUBLIC;
GRANT ALL PRIVILEGES ON TABLE public.youtube_videos TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.youtube_videos_id_seq TO service_role;
COMMIT;
